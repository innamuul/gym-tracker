"""Builds data/bodymap.js (window.GYM_BODY) from react-native-body-highlighter (MIT, (c) 2022 ELABBASSI Hicham).
   https://github.com/HichamELBSI/react-native-body-highlighter
Usage: python tools/build_bodymap.py <folder with bodyFront.ts, bodyBack.ts, SvgMaleWrapper.tsx>
Each part becomes [slug, [path d, ...]]; app.js maps slugs to its own muscle names (BODY_MAP)."""
import json, os, re, sys

src = sys.argv[1]
OUT = os.path.join(os.path.dirname(__file__), '..', 'data', 'bodymap.js')


def parts(fn):
    txt = open(os.path.join(src, fn), encoding='utf-8').read()
    out = []
    # every part is { slug: "x", ... path: { left/right/common: ["d", ...] } }
    for m in re.finditer(r'slug:\s*"([a-z-]+)"(.*?)(?=\n  \{|\n\];)', txt, re.S):
        ds = re.findall(r'"(M[^"]+)"', m.group(2))
        if ds:
            out.append([m.group(1), ds])
    return out


wrap = open(os.path.join(src, 'SvgMaleWrapper.tsx'), encoding='utf-8').read()
outlines = re.findall(r'd="(M [^"]+)"', wrap)
data = {
    'front': {'vb': '0 0 724 1448', 'outline': outlines[0], 'parts': parts('bodyFront.ts')},
    'back': {'vb': '724 0 724 1448', 'outline': outlines[1], 'parts': parts('bodyBack.ts')},
}
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('/* Body map shapes: react-native-body-highlighter by ELABBASSI Hicham, MIT License\n'
            '   https://github.com/HichamELBSI/react-native-body-highlighter (generated by tools/build_bodymap.py) */\n')
    f.write('window.GYM_BODY=' + json.dumps(data, separators=(',', ':')) + ';\n')
print({k: [p[0] for p in v['parts']] for k, v in data.items()}, os.path.getsize(OUT), 'bytes')
